#!/usr/bin/env bash
# Generate the local/kind development credentials.
#
# A fresh clone has no credentials: deploy/kubernetes/02-secrets-dev.yaml is
# git-ignored and this script creates it. `make up` and `make deploy` call it
# automatically.
#
# These values are only for a throwaway local cluster. A deployed environment
# must inject its own Secret; the homelab does that from the private
# infrastructure repository (SOPS-encrypted), never from here.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="${ROOT}/deploy/kubernetes/02-secrets-dev.yaml"

if [ -f "${OUT}" ] && [ "${1:-}" != "--force" ]; then
  echo "==> dev credentials already exist: deploy/kubernetes/02-secrets-dev.yaml"
  exit 0
fi

rand() { openssl rand -hex 24; }

# This seed is deliberately fixed, and is NOT a credential. The matching public
# key is pinned in shared/src/dev-attestation.ts; simulated attestation only
# verifies with this keypair. Production removes the dev key entirely.
ATTESTATION_KEY="qSgP+dPwGhb/58O0ZD/dSqCMovhhWNIQbT3MeTD35WY="

umask 077
cat > "${OUT}" <<EOF
# GENERATED by scripts/dev-secrets.sh. Do not commit.
#
# Throwaway local-cluster credentials. Nothing here should reach a deployed
# environment: the homelab injects its own Secret from the private repo.
apiVersion: v1
kind: Secret
metadata:
  name: x402-secrets
  namespace: sandbox-system
type: Opaque
stringData:
  admin-token: "$(rand)"
  relay-admin-token: "$(rand)"
  # Low-privilege token: the relay may only nudge the reconciler.
  wake-token: "$(rand)"
  proxy-token-secret: "$(rand)"
  # HMAC key for deriving session capabilities from settled payments.
  capability-secret: "$(rand)"
  # Ed25519 seed (32 bytes, base64) for simulated attestation. Published test
  # key: the public half is pinned in shared/src/dev-attestation.ts.
  dev-attestation-key: "${ATTESTATION_KEY}"
  dev-attestation-key-id: "x402-dev-attestation-key"
EOF
chmod 600 "${OUT}"
echo "==> generated deploy/kubernetes/02-secrets-dev.yaml (git-ignored)"
