#!/usr/bin/env bash
# Apply all manifests, including the dynamically rendered NetworkPolicy that
# allows the controller to reach the kube-apiserver on the node IP.
#
# Why dynamic: with kube-proxy (Cilium kubeProxyReplacement=false) the
# in-cluster Service IP 10.96.0.1:443 is DNAT'ed to <node-ip>:6443 before egress
# policy is evaluated, so a static ipBlock cannot express it portably.
set -euo pipefail

CONTEXT="${CONTEXT:-kind-x402-sandbox}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

kubectl --context "${CONTEXT}" apply -k "${ROOT}/deploy/kubernetes"

# The shipped Service is ClusterIP: nothing outside the cluster should reach the
# API over plaintext. kind's extraPortMapping (host :8080 -> node :30080) is a
# local convenience, so opt back into a NodePort here — and only here. Removing
# this patch is what makes `kind` match production exposure.
kubectl --context "${CONTEXT}" -n sandbox-system patch svc api --type merge -p \
  '{"spec":{"type":"NodePort","ports":[{"name":"http","port":3000,"targetPort":3000,"nodePort":30080}]}}'

if kubectl --context "${CONTEXT}" get crd ciliumnetworkpolicies.cilium.io >/dev/null 2>&1; then
  echo "==> Cilium detected: applying entity-based apiserver egress policy"
  kubectl --context "${CONTEXT}" apply -f "${ROOT}/deploy/kubernetes/cilium/controller-apiserver.yaml"
fi

mapfile -t NODE_IPS < <(
  kubectl --context "${CONTEXT}" get nodes \
    -o jsonpath='{range .items[*]}{.status.addresses[?(@.type=="InternalIP")].address}{"\n"}{end}'
)

if [ "${#NODE_IPS[@]}" -eq 0 ]; then
  echo "error: could not determine node IPs" >&2
  exit 1
fi

{
  cat <<'EOF'
# Generated by deploy/kind/apply.sh: controller -> kube-apiserver on node IPs.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: allow-controller-k8s-api-node
  namespace: sandbox-system
spec:
  podSelector:
    matchLabels: {app: controller}
  policyTypes: ["Egress"]
  egress:
EOF
  for ip in "${NODE_IPS[@]}"; do
    cat <<EOF
    - to:
        - ipBlock:
            cidr: ${ip}/32
      ports:
        - protocol: TCP
          port: 6443
EOF
  done
} | kubectl --context "${CONTEXT}" apply -f -

echo "==> applied (kube-apiserver egress: ${NODE_IPS[*]}):6443"
