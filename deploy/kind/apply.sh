#!/usr/bin/env bash
# Apply all manifests, including the dynamically rendered NetworkPolicy that
# allows the controller to reach the kube-apiserver on the node IP.
#
# Why dynamic: with kube-proxy (Cilium kubeProxyReplacement=false) the
# in-cluster Service IP 10.96.0.1:443 is DNAT'ed to <node-ip>:6443 before egress
# policy is evaluated, so a static ipBlock cannot express it portably.
set -euo pipefail

CONTEXT="${CONTEXT:-kind-x402-sandbox}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
GUEST_IMAGE="${GUEST_IMAGE:-x402-sandbox/guest:dev}"
# Which overlay to render. The base deploy is runc; deploy/kata flips the
# RuntimeClass handler and EXECUTION_MODE. Both go through the same digest
# pinning below, which is why the gate can apply the Kata overlay at all.
KUSTOMIZE_DIR="${KUSTOMIZE_DIR:-${ROOT}/deploy/kubernetes}"

# kind has no registry, so a `repo@sha256:…` reference cannot be pulled unless
# the digest itself exists as an image record in the node's containerd. The
# controller refuses to start with the dev placeholder when Kubernetes is
# enabled, so pin the locally built image by its real digest and apply that.
pin_guest_image_digest() {
  local image="$1"
  local ref="$image"
  local first="${image%%/*}"
  local digest="" node node_digest
  case "${first}" in
    *.*|*:*|localhost) ;;
    *) ref="docker.io/${image}" ;;
  esac

  while IFS= read -r node; do
    [ -n "${node}" ] || continue
    node_digest="$(docker exec "${node}" ctr -n k8s.io images ls 2>/dev/null \
      | awk -v ref="${ref}" '$1 == ref { print $3; exit }')"
    if [ -z "${node_digest}" ]; then
      echo "error: ${image} is not loaded on kind node ${node} (run make build first)" >&2
      return 1
    fi
    if [ -z "${digest}" ]; then
      digest="${node_digest}"
    elif [ "${digest}" != "${node_digest}" ]; then
      echo "error: ${image} digest differs between kind nodes: ${digest} vs ${node_digest}" >&2
      return 1
    fi
    docker exec "${node}" ctr -n k8s.io images tag "${ref}" "${ref%:*}@${digest}" >/dev/null
  done < <(kubectl --context "${CONTEXT}" get nodes -o name | sed 's|^node/||')

  if [[ ! "${digest}" =~ ^sha256:[0-9a-f]{64}$ ]]; then
    echo "error: could not determine a pinned digest for ${image}" >&2
    return 1
  fi
  printf '%s\n' "${digest}"
}

GUEST_DIGEST="$(pin_guest_image_digest "${GUEST_IMAGE}")"
MANIFESTS="$(kubectl --context "${CONTEXT}" kustomize "${KUSTOMIZE_DIR}")"
if ! grep -Fq 'GUEST_IMAGE_DIGEST: sha256:dev-unpinned-image' <<<"${MANIFESTS}"; then
  echo "error: could not find the placeholder GUEST_IMAGE_DIGEST to pin in deploy/kubernetes" >&2
  exit 1
fi

# Credentials are generated locally and git-ignored. Apply the namespaces and the
# Secret before the workloads so the first pod start does not race an absent
# Secret (CreateContainerConfigError until the next kubelet retry).
"${ROOT}/scripts/dev-secrets.sh"
kubectl --context "${CONTEXT}" apply -f "${ROOT}/deploy/kubernetes/00-namespaces.yaml"
kubectl --context "${CONTEXT}" apply -f "${ROOT}/deploy/kubernetes/02-secrets-dev.yaml"

# Guest-image admission (deploy/kubernetes/kyverno/). A locally built image has a
# machine-specific digest, which a committed allowlist cannot contain, so on kind
# the namespace drops only the released-digest rule. The repository+digest-shape
# rule still applies. No-op when Kyverno is not installed.
if kubectl --context "${CONTEXT}" get crd clusterpolicies.kyverno.io >/dev/null 2>&1; then
  kubectl --context "${CONTEXT}" label namespace sandbox-workloads \
    x402.io/image-policy=dev-unpinned --overwrite
fi

printf '%s\n' "${MANIFESTS}" \
  | sed "s|GUEST_IMAGE_DIGEST: sha256:dev-unpinned-image|GUEST_IMAGE_DIGEST: ${GUEST_DIGEST}|" \
  | kubectl --context "${CONTEXT}" apply -f -

# The shipped Service is ClusterIP: nothing outside the cluster should reach the
# API over plaintext. kind's extraPortMapping (host :8080 -> node :30080) is a
# local convenience, so opt back into a NodePort here — and only here. Removing
# this patch is what makes `kind` match production exposure.
kubectl --context "${CONTEXT}" -n sandbox-system patch svc api --type merge -p \
  '{"spec":{"type":"NodePort","ports":[{"name":"http","port":3000,"targetPort":3000,"nodePort":30080}]}}'

if kubectl --context "${CONTEXT}" get crd ciliumnetworkpolicies.cilium.io >/dev/null 2>&1; then
  echo "==> Cilium detected: applying entity-based apiserver egress policy"
  kubectl --context "${CONTEXT}" apply -f "${ROOT}/deploy/kubernetes/cilium/controller-apiserver.yaml"
fi

mapfile -t NODE_IPS < <(
  kubectl --context "${CONTEXT}" get nodes \
    -o jsonpath='{range .items[*]}{.status.addresses[?(@.type=="InternalIP")].address}{"\n"}{end}'
)

if [ "${#NODE_IPS[@]}" -eq 0 ]; then
  echo "error: could not determine node IPs" >&2
  exit 1
fi

{
  cat <<'EOF'
# Generated by deploy/kind/apply.sh: controller -> kube-apiserver on node IPs.
apiVersion: networking.k8s.io/v1
kind: NetworkPolicy
metadata:
  name: allow-controller-k8s-api-node
  namespace: sandbox-system
spec:
  podSelector:
    matchLabels: {app: controller}
  policyTypes: ["Egress"]
  egress:
EOF
  for ip in "${NODE_IPS[@]}"; do
    cat <<EOF
    - to:
        - ipBlock:
            cidr: ${ip}/32
      ports:
        - protocol: TCP
          port: 6443
EOF
  done
} | kubectl --context "${CONTEXT}" apply -f -

echo "==> applied (kube-apiserver egress: ${NODE_IPS[*]}):6443"
